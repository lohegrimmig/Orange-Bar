let current = 'en';

export function detectLang() {
  // Standard-Startseite ist bewusst Englisch (für alle gleich). Nur eine
  // ausdrücklich gewählte Sprache überschreibt das – dann bleibt sie gespeichert.
  const saved = localStorage.getItem('ob_lang');
  if (saved && STR[saved]) return saved;
  return 'en';
}

export function setLang(code) {
  if (!STR[code]) code = 'en';
  current = code;
  localStorage.setItem('ob_lang', code);
  const meta = LANGS.find((l) => l.code === code) || LANGS[0];
  document.documentElement.lang = code;
  document.documentElement.dir = meta.dir;
  applyI18n();
}

export function getLang() { return current; }

/** Übersetzt einen Schlüssel (Fallback: Englisch, dann der Schlüssel selbst). */
export function t(key) {
  return (STR[current] && STR[current][key]) || STR.en[key] || key;
}

/** Ersetzt alle data-i18n / data-i18n-ph (Platzhalter) unter root. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
}
